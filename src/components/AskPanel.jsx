import { useEffect, useRef, useState } from "react";
import Markdown from "./Markdown";
import { githubFileUrl } from "../lib/github";
import { suggestedQuestions } from "../lib/analyze";

const Citation = ({ repo, c }) => {
  const label = c.startLine ? `${c.path}:${c.startLine}${c.endLine && c.endLine !== c.startLine ? `–${c.endLine}` : ""}` : c.path;
  return (
    <li className="citation">
      <a className="cite-chip" href={githubFileUrl(repo, c.path, c.startLine, c.endLine)} target="_blank" rel="noopener noreferrer">
        {label}
      </a>
      {c.note && <span className="cite-note">{c.note}</span>}
      {c.snippet && (
        <pre className="cite-snippet">
          <code>{c.snippet}</code>
        </pre>
      )}
    </li>
  );
};

const Answer = ({ repo, msg }) => {
  if (msg.pending) {
    return (
      <p className="answer-pending" aria-live="polite">
        <span className="pulse" aria-hidden="true" /> Searching the code…
      </p>
    );
  }
  return (
    <div className="answer">
      {msg.source === "ai" ? <Markdown text={msg.text} /> : <p className="answer-text">{msg.text}</p>}
      {msg.code && (
        <pre className="code-block">
          <code>{msg.code}</code>
        </pre>
      )}
      {msg.citations?.length > 0 && (
        <ul className="citations" aria-label="Sources">
          {msg.citations.map((c, i) => (
            <Citation key={`${c.path}-${c.startLine || 0}-${i}`} repo={repo} c={c} />
          ))}
        </ul>
      )}
      {msg.source === "search" && <p className="answer-source">Found by searching the repository files, not generated by AI.</p>}
    </div>
  );
};

const AskPanel = ({ analysis }) => {
  const { repo, overview, messages, asking, ask } = analysis;
  const [value, setValue] = useState("");
  const listRef = useRef(null);
  const inputRef = useRef(null);

  useEffect(() => {
    const el = listRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages]);

  const submit = (text) => {
    const q = (text ?? value).trim();
    if (!q || asking) return;
    ask(q);
    setValue("");
  };

  return (
    <aside className="ask" aria-label={`Ask about ${repo.fullName}`}>
      <h2 className="ask-title">Ask about this repo</h2>
      <div className="ask-thread" ref={listRef}>
        {messages.length === 0 ? (
          <ul className="suggestions">
            {suggestedQuestions(overview).map((q) => (
              <li key={q}>
                <button type="button" className="suggestion" onClick={() => submit(q)}>
                  {q}
                </button>
              </li>
            ))}
          </ul>
        ) : (
          messages.map((m) =>
            m.role === "user" ? (
              <p key={m.id} className="question">
                {m.text}
              </p>
            ) : (
              <Answer key={m.id} repo={repo} msg={m} />
            )
          )
        )}
      </div>
      <form
        className="ask-form"
        onSubmit={(e) => {
          e.preventDefault();
          submit();
        }}
      >
        <label htmlFor="ask-input" className="sr-only">
          Your question
        </label>
        <textarea
          id="ask-input"
          ref={inputRef}
          className="ask-input"
          rows={1}
          placeholder="Where is auth handled?"
          value={value}
          onChange={(e) => setValue(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault();
              submit();
            }
          }}
        />
        <button type="submit" className="ask-submit" disabled={asking || !value.trim()}>
          Ask
        </button>
      </form>
    </aside>
  );
};

export default AskPanel;
